"""Put the owner's Siamese cat drawings into the site and generate the shared grids.

Outputs (repo):
  public/study/cat.webp          cartoon, 720 px tall, original framing
  public/study/cat-pixel.webp    pixel-art version, transparent background, 720 px tall
  public/study/cat-square.png    cartoon padded to a square around the cat, 512 x 512 (canvas scenes crop patches from this)
  components/study/cat-grids.ts  import-free numbers measured from cat-square.png
"""
import io, json
from PIL import Image

IMG = 'E:/OneDrive/Documents/THU/CV/study-assets/'
REPO = 'E:/OneDrive/Documents/THU/CV/joongwon-research-website/'
BG = (253, 236, 226)

cartoon = Image.open(IMG + 'siamese-cartoon.webp').convert('RGB')
pixel = Image.open(IMG + 'siamese-pixel.webp').convert('RGBA')

def by_height(im, h):
    w = round(im.width * h / im.height)
    return im.resize((w, h), Image.LANCZOS)

by_height(cartoon, 720).save(REPO + 'public/study/cat.webp', quality=88)
by_height(pixel, 720).save(REPO + 'public/study/cat-pixel.webp', quality=92, lossless=False)

# bounding box of the cat in the cartoon: pixels clearly different from the background
W, H = cartoon.size
px = cartoon.load()
xs, ys = [], []
for y in range(0, H, 2):
    for x in range(0, W, 2):
        r, g, b = px[x, y]
        if abs(r - BG[0]) + abs(g - BG[1]) + abs(b - BG[2]) > 40:
            xs.append(x); ys.append(y)
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
side = int(max(x1 - x0, y1 - y0) * 1.06)
cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
sq = Image.new('RGB', (side, side), BG)
sq.paste(cartoon, (side // 2 - cx, side // 2 - cy))
sq = sq.resize((512, 512), Image.LANCZOS)
sq.save(REPO + 'public/study/cat-square.png')

def classify(rgb):
    r, g, b = rgb
    if b > r + 15 and b > 120: return 'eye'
    if abs(r - BG[0]) + abs(g - BG[1]) + abs(b - BG[2]) < 30: return 'bg'
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    if lum < 110: return 'point'
    if r > g + 40 and lum < 170: return 'ear'
    return 'cream'

def grids(n, sq):
    small = sq.resize((n, n), Image.BOX)
    sp = small.load()
    gray, rgb = [], []
    for j in range(n):
        gr, rr = [], []
        for i in range(n):
            r, g, b = sp[i, j]
            gr.append(round((0.299 * r + 0.587 * g + 0.114 * b) / 255, 2))
            rr.append([round(r / 255, 2), round(g / 255, 2), round(b / 255, 2)])
        gray.append(gr); rgb.append(rr)
    # dominant part per cell, from the full-resolution square
    cell = 512 // n if 512 % n == 0 else 512 / n
    big = sq.load()
    parts = []
    for j in range(n):
        row = []
        for i in range(n):
            counts = {}
            for y in range(int(j * 512 / n), int((j + 1) * 512 / n), 2):
                for x in range(int(i * 512 / n), int((i + 1) * 512 / n), 2):
                    k = classify(big[x, y]); counts[k] = counts.get(k, 0) + 1
            # eyes are small; mark a cell as eye if at least 8% of it is eye
            tot = sum(counts.values())
            if counts.get('eye', 0) / tot >= 0.08: row.append('eye')
            else: row.append(max(counts, key=counts.get))
        parts.append(row)
    return gray, rgb, parts

out = {}
lines = ['/** Numbers measured from the owner\'s Siamese cat drawing (public/study/cat-square.png, 512 x 512).',
         ' *  Generated by scripts/prep_cat.py; do not edit by hand. Gray = luminance 0..1 (0 dark, 1 bright).',
         ' *  RGB = 0..1 per channel. PARTS = dominant part per cell: bg, cream (body fur), point (dark ears, mask, legs, tail), ear (pink inner ear), eye. */', '']
head = cartoon.crop((375, 5, 885, 515)).resize((512, 512), Image.LANCZOS)
head.save(REPO + 'public/study/cat-head.png')
lines.append('/* Whole cat, padded to a square (cat-square.png). */')
for n in [2, 4, 8, 9, 16, 32, 64]:
    gray, rgb, parts = grids(n, sq)
    out[n] = {'gray': gray, 'parts': parts}
    lines.append(f'export const CAT_GRAY_{n}: number[][] = {json.dumps(gray)};')
    lines.append(f'export const CAT_PARTS_{n}: string[][] = {json.dumps(parts)};')
    if n in (2, 4, 8, 16, 32):
        lines.append(f'export const CAT_RGB_{n}: number[][][] = {json.dumps(rgb)};')
    lines.append('')
lines.append('/* Head only: ears, face mask and eyes fill the frame (cat-head.png). */')
head_out = {}
for n in [2, 4, 8, 9, 16]:
    gray, rgb, parts = grids(n, head)
    head_out[n] = parts
    lines.append(f'export const CAT_HEAD_GRAY_{n}: number[][] = {json.dumps(gray)};')
    lines.append(f'export const CAT_HEAD_PARTS_{n}: string[][] = {json.dumps(parts)};')
    lines.append(f'export const CAT_HEAD_RGB_{n}: number[][][] = {json.dumps(rgb)};')
    lines.append('')
lines.append('export const CAT_SRC = { cartoon: "/study/cat.webp", pixel: "/study/cat-pixel.webp", square: "/study/cat-square.png", head: "/study/cat-head.png" };')
io.open(REPO + 'components/study/cat-grids.ts', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')

sym = {'bg': '.', 'cream': 'c', 'point': 'P', 'ear': 'e', 'eye': 'O'}
for n in [8, 9]:
    print(f'--- head {n}x{n} parts')
    for row in head_out[n]:
        print(' '.join(sym[k] for k in row))
# contact sheet for a visual check
sheet = Image.new('RGB', (6 * 210, 210), (246, 247, 251))
tiles = [sq, sq.resize((16, 16), Image.BOX), sq.resize((9, 9), Image.BOX), head, head.resize((9, 9), Image.BOX), head.resize((2, 2), Image.BOX)]
for k, t in enumerate(tiles):
    sheet.paste(t.resize((200, 200), Image.NEAREST), (k * 210 + 5, 5))
sheet.save(IMG + 'cat_sheet.png')
for n in [8, 9, 16]:
    print(f'--- {n}x{n} parts')
    for row in out[n]['parts']:
        print(' '.join({'bg': '.', 'cream': 'c', 'point': 'P', 'ear': 'e', 'eye': 'O'}[k] for k in row))
print('square bbox', x0, y0, x1, y1, 'side', side)
